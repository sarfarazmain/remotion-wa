// 4. SfxMap.ts — Sound Effect trigger events mapped to absolute frames
// ══════════════════════════════════════════════════════════════════════════════

interface SfxManifestEntry {
    file: string;
    volume: number;
    freesoundId: number;
    name: string;
    duration: number;
    license: string;
    onsetSec?: number;    // seconds of leading silence to skip
}

function generateSfxMap(
    topic: TopicJSON,
    sceneTimings: SceneTiming[],
    sfxManifest: Record<string, SfxManifestEntry>,
): string {
    if (Object.keys(sfxManifest).length === 0) {
        return `/**\n * SfxMap — No SFX available\n */\nexport interface SfxEvent { absoluteFrame: number; sfxFile: string; volume: number; startFrom: number; label: string; }\nexport const SFX_EVENTS: SfxEvent[] = [];\n`;
    }

    // Build cumulative scene starts
    const starts: number[] = [];
    let cum = 0;
    for (const t of sceneTimings) {
        starts.push(cum);
        cum += t.durationFrames;
    }

    const FPS_SFX = 30;
    const events: Array<{ absoluteFrame: number; sfxFile: string; volume: number; startFrom: number; label: string }> = [];
    const HOLD_EVOLVE_AT = 90; // from PacingEngine PACING constant

    // Helper: convert onset seconds → frames, rounding down for safety
    const onsetFrames = (key: string): number => {
        const sec = sfxManifest[key]?.onsetSec ?? 0;
        return Math.floor(sec * FPS_SFX);
    };

    for (let i = 0; i < topic.scenes.length; i++) {
        const scene = topic.scenes[i];
        const sceneStart = starts[i];
        const sceneDur = sceneTimings[i].durationFrames;
        const cues = sceneTimings[i].cuePoints;

        // Helper: get cue frame offset for this scene
        const getCue = (event: string): number => {
            const cue = cues.find((c) => c.event === event);
            return cue ? cue.frameOffset : 0;
        };

        // ── STOMP_IMPACT: fires at HERO_WORD for scenes with STOMP typography
        if (sfxManifest["STOMP_IMPACT"] && scene.typography?.lines.some((l: any) => l.animation === "STOMP")) {
            events.push({
                absoluteFrame: sceneStart + getCue("HERO_WORD"),
                sfxFile: sfxManifest["STOMP_IMPACT"].file,
                volume: sfxManifest["STOMP_IMPACT"].volume,
                startFrom: onsetFrames("STOMP_IMPACT"),
                label: `S${scene.index} STOMP @ HERO_WORD`,
            });
        }

        // ── CHART_DRAW: fires at CHART_DRAW_START for chart scenes
        if (sfxManifest["CHART_DRAW"] && scene.chart) {
            events.push({
                absoluteFrame: sceneStart + getCue("CHART_DRAW_START"),
                sfxFile: sfxManifest["CHART_DRAW"].file,
                volume: sfxManifest["CHART_DRAW"].volume,
                startFrom: onsetFrames("CHART_DRAW"),
                label: `S${scene.index} CHART_DRAW`,
            });
        }

        // ── HIGHLIGHTER_CIRCLE: fires at Hold & Evolve trigger (f90) for HIGHLIGHTER scenes
        if (sfxManifest["HIGHLIGHTER_CIRCLE"] && scene.microReset?.type === "HIGHLIGHTER" && sceneDur > HOLD_EVOLVE_AT) {
            events.push({
                absoluteFrame: sceneStart + HOLD_EVOLVE_AT,
                sfxFile: sfxManifest["HIGHLIGHTER_CIRCLE"].file,
                volume: sfxManifest["HIGHLIGHTER_CIRCLE"].volume,
                startFrom: onsetFrames("HIGHLIGHTER_CIRCLE"),
                label: `S${scene.index} HIGHLIGHTER @ f${HOLD_EVOLVE_AT}`,
            });
        }

        // ── REDACTION_REVEAL: fires at Hold & Evolve trigger for REDACTION scenes
        if (sfxManifest["REDACTION_REVEAL"] && scene.microReset?.type === "REDACTION_REVEAL" && sceneDur > HOLD_EVOLVE_AT) {
            events.push({
                absoluteFrame: sceneStart + HOLD_EVOLVE_AT,
                sfxFile: sfxManifest["REDACTION_REVEAL"].file,
                volume: sfxManifest["REDACTION_REVEAL"].volume,
                startFrom: onsetFrames("REDACTION_REVEAL"),
                label: `S${scene.index} REDACTION_REVEAL @ f${HOLD_EVOLVE_AT}`,
            });
        }
    }

    // ── Transition SFX: fire at scene boundary (= start of destination scene)
    // The camera whip-pan / visual transition starts exactly at the boundary
    // between source and destination scenes, so SFX must hit at that instant.
    for (const t of topic.transitions) {
        const toIdx = t.to - 1; // 0-indexed destination scene
        const transFrame = starts[toIdx]; // exact scene boundary

        if (t.type === "Z_AXIS_PORTAL" && sfxManifest["Z_AXIS_SWOOSH"]) {
            events.push({
                absoluteFrame: transFrame,
                sfxFile: sfxManifest["Z_AXIS_SWOOSH"].file,
                volume: sfxManifest["Z_AXIS_SWOOSH"].volume,
                startFrom: onsetFrames("Z_AXIS_SWOOSH"),
                label: `S${t.from}→S${t.to} Z_AXIS_PORTAL`,
            });
        }
        if (t.type === "FLASHBULB" && sfxManifest["FLASHBULB_SHUTTER"]) {
            events.push({
                absoluteFrame: transFrame,
                sfxFile: sfxManifest["FLASHBULB_SHUTTER"].file,
                volume: sfxManifest["FLASHBULB_SHUTTER"].volume,
                startFrom: onsetFrames("FLASHBULB_SHUTTER"),
                label: `S${t.from}→S${t.to} FLASHBULB`,
            });
        }
        if (t.type === "INK_BLEED" && sfxManifest["INK_BLEED"]) {
            events.push({
                absoluteFrame: transFrame,
                sfxFile: sfxManifest["INK_BLEED"].file,
                volume: sfxManifest["INK_BLEED"].volume,
                startFrom: onsetFrames("INK_BLEED"),
                label: `S${t.from}→S${t.to} INK_BLEED`,
            });
        }
    }

    // Sort by absolute frame
    events.sort((a, b) => a.absoluteFrame - b.absoluteFrame);

    // Generate TypeScript
    const lines = [
        `/**`,
        ` * SfxMap — Sound Effect Events`,
        ` * ─────────────────────────────`,
        ` * GENERATED by pipeline/stages/generate.ts — DO NOT EDIT MANUALLY`,
        ` * Topic: "${topic.meta.title}" (${topic.meta.slug})`,
        ` * ${events.length} SFX events mapped to absolute frames`,
        ` */`,
        ``,
        `export interface SfxEvent {`,
        `    absoluteFrame: number;`,
        `    sfxFile: string;`,
        `    volume: number;`,
        `    startFrom: number;`,
        `    label: string;`,
        `}`,
        ``,
        `export const SFX_EVENTS: SfxEvent[] = [`,
    ];

    for (const evt of events) {
        lines.push(`    { absoluteFrame: ${evt.absoluteFrame}, sfxFile: "${evt.sfxFile}", volume: ${evt.volume}, startFrom: ${evt.startFrom}, label: "${evt.label}" },`);
    }

    lines.push(`];`);
    lines.push(``);

    return lines.join("\n");
}

export function generateAllFiles(
    topic: TopicJSON,
    sceneTimings: SceneTiming[],
    assetManifest: Record<string, string>,
    sfxManifest?: Record<string, SfxManifestEntry>,
): { pacingPath: string; syncPath: string; dataPath: string; sfxPath?: string } {
    console.log("  🔧 Generating PacingEngine.ts...");
    const pacingContent = generatePacingEngine(sceneTimings, topic);
    const pacingPath = `${OUTPUT_DIR}/PacingEngine.ts`;
    writeFileSync(pacingPath, pacingContent);

    console.log("  🔧 Generating AudioSyncMap.ts...");
    const syncContent = generateAudioSyncMap(sceneTimings, topic);
    const syncPath = `${OUTPUT_DIR}/AudioSyncMap.ts`;
    writeFileSync(syncContent.length > 0 ? syncPath : syncPath, syncContent);

    console.log("  🔧 Generating topicData.ts...");
    const dataContent = generateTopicData(topic, assetManifest);
    const dataPath = `${OUTPUT_DIR}/topicData.ts`;
    writeFileSync(dataPath, dataContent);

    let sfxPath: string | undefined;
    if (sfxManifest && Object.keys(sfxManifest).length > 0) {
        console.log("  🔧 Generating SfxMap.ts...");
        const sfxContent = generateSfxMap(topic, sceneTimings, sfxManifest);
        sfxPath = `${OUTPUT_DIR}/SfxMap.ts`;
        writeFileSync(sfxPath, sfxContent);
        console.log(`  ✅ Generated 4 files to ${OUTPUT_DIR}/`);
    } else {
        console.log(`  ✅ Generated 3 files to ${OUTPUT_DIR}/`);
    }

    return { pacingPath, syncPath, dataPath, sfxPath };
}
